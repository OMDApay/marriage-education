export const getPositionById = (id) => {
  return sexualPositions.find(position => position.id === id)
}

export const getPositionsByCategory = (category) => {
  return sexualPositions.filter(position => position.category === category)
}

export const searchPositions = (query) => {
  const lowercaseQuery = query.toLowerCase()
  return sexualPositions.filter(position => 
    position.title.toLowerCase().includes(lowercaseQuery) ||
    position.arabicTitle.toLowerCase().includes(lowercaseQuery) ||
    position.description.toLowerCase().includes(lowercaseQuery) ||
    position.tags.some(tag => tag.toLowerCase().includes(lowercaseQuery))
  )
}

export const getAllCategories = () => {
  const categories = [...new Set(sexualPositions.map(position => position.category))]
  return categories
}

