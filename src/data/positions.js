// استيراد الصور
const importPositionImages = () => {
  const images = {}
  try {
    // استيراد جميع الصور من مجلد الأوضاع
    const imageModules = import.meta.glob('../assets/positions/*.{jpg,jpeg,png,webp}', { eager: true })
    
    Object.entries(imageModules).forEach(([path, module]) => {
      const fileNameWithExtension = path.split('/').pop()
      const fileName = fileNameWithExtension.slice(0, fileNameWithExtension.lastIndexOf('.'))
      images[fileName] = module.default
    })
  } catch (error) {
    console.log('Error loading position images:', error)
  }
  return images
}

