def word_count(text):
    return len(re.findall(r"\S+", text))

def generate(item, attempt=0):
    client = OpenAI()
    extra = '' if attempt == 0 else '\nهذه محاولة توسعة ثانية. المسودة السابقة كانت أقصر من المطلوب؛ اكتب الآن ما لا يقل عن 1400 كلمة عربية فعلية مع تفاصيل عملية إضافية وأمثلة واقعية غير شخصية.'
    prompt = COMMON + extra + f"\nعنوان المقال: {item['title']}\nالمحور الخاص: {item['focus']}"
    resp = client.chat.completions.create(
        model=MODEL,
        messages=[
            {'role':'system','content':'اكتب محتوى تثقيفياً طبياً دقيقاً ومحترماً، ولا تضع معلومات غير موثقة.'},
            {'role':'user','content':prompt},
        ],
        max_completion_tokens=5200,
        extra_body={'reasoning': {'effort': 'minimal'}},
    )
    text = resp.choices[0].message.content.strip()
    return {**item, 'content': text, 'wordCount': word_count(text)}

def main():
    results = []
    with cf.ThreadPoolExecutor(max_workers=5) as ex:
        first = list(ex.map(generate, ARTICLES))
    with cf.ThreadPoolExecutor(max_workers=5) as ex:
        jobs = [(item, 1) if item['wordCount'] < 1000 else (item, None) for item in first]
        def maybe_retry(job):
            item, attempt = job
            return generate({k:item[k] for k in ('id','title','focus')}, attempt) if attempt else item
        results = list(ex.map(maybe_retry, jobs))
    short = [r['id'] for r in results if r['wordCount'] < 1000]
    if short:
        raise RuntimeError(f'Articles below 1000 words after retry: {short}')
    OUT.write_text(json.dumps(results, ensure_ascii=False, indent=2), encoding='utf-8')
    print(json.dumps({'output': str(OUT), 'counts': {r['id']: r['wordCount'] for r in results}}, ensure_ascii=False, indent=2))

if __name__ == '__main__':
    main()
